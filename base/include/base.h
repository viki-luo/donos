/*
 * base.h — liteOS 基座接口（硬件无关）
 *
 * 基座是一个无状态的运动控制函数：
 *
 *     基座 = f(自描述的运动控制事件) → 对物件施加运动
 *
 * 三条不变量（任何实现都不得违反）：
 *
 *   1. 无状态 —— 基座不保存任何世界信息。
 *   2. 接线 ≠ 信息 —— 基座可持有接线（谁挂在哪个口），绝不持有内容。
 *   3. 唯一原语 —— 只有「施加运动」；「静止」即 motion 取零。
 *
 * 任何在本文件之外出现的「停止」「查询状态」「记录历史」接口，
 * 都是设计违规。
 */
#ifndef LITEOS_BASE_H
#define LITEOS_BASE_H

#include "types.h"

/*
 * 定点数与量纲（设计决定 18，冻结）
 * -----------------
 * 基座不碰浮点。所有运动量以定点表示：
 *   高 32 位为整数部分，低 32 位为小数部分（Q32.32）。
 *
 * motion 的量纲在通道上冻结，不随物件变化：
 *   motion[0..2]  线速度，m/s
 *   motion[3..5]  角速度，rad/s
 * 物件按自己申报的 period_ns 把速度积分到位姿——同一事件在不同周期的
 * 物件上产生相同的世界速度。设备原生单位（度、编码器 tick、毫米）
 * 由物件适配层换算，不进入基座通道。
 */
typedef int64_t motion_fixed_t;

#define MOTION_DOF_MAX 6

/*
 * 接线句柄。0 为无效。
 *
 * 编码：(世代号 << 16) | (槽位序号 + 1)
 *
 * 为什么带世代号 —— 在一个热插拔系统里，句柄必须跨「槽位复用」保持稳定。
 * 否则旧大脑缓存着 wire 7，那个物件离开后新物件正好占用 7 号槽，
 * 旧大脑就会对着一个陌生的物件下指令；在物理世界里这就是事故。
 *
 * 有了世代号，离开的句柄永远不会再指向任何东西：它是个死句柄，
 * 而不是「指向别人的句柄」。
 */
typedef uint64_t wire_t;
#define WIRE_NONE 0

#define WIRE_INDEX(w)       ((u32)((w) & 0xFFFFu))
#define WIRE_GEN(w)         ((u32)((w) >> 16))
#define WIRE_MAKE(gen, idx) (((wire_t)(gen) << 16) | (wire_t)(idx))

/*
 * 句柄只使用低 48 位：世代号 32 位（位 16..47）+ 槽位 16 位（位 0..15）。
 * 高 16 位（位 48..63）必须为 0 —— WIRE_GEN 会右移后截断，若高位置位，
 * 同一句柄会出现多个非规范别名，校验时必须拒绝它们。
 */
#define WIRE_CANONICAL_MASK ((wire_t)0x0000FFFFFFFFFFFFull)

/* 世界坐标系：所有运动最终的参照。 */
#define FRAME_WORLD 0

/* ------------------------------------------------------------------ */
/* 运动控制事件                                                        */
/*                                                                    */
/* 这是基座唯一认识的数据。它必须自描述：                             */
/*   - 目标是谁      (wire)                                           */
/*   - 相对谁        (frame)                                          */
/*   - 何时发出      (issued_at_ns)                                   */
/*   - 多久内仍新鲜  (duration_ns)                                    */
/*   - 怎么动        (motion[])                                       */
/*                                                                    */
/* 刻意不含任何 opaque 载荷。其它信息走物件与大脑的直连通道。          */
/* ------------------------------------------------------------------ */

typedef struct {
        wire_t          wire;          /* 目标接线；WIRE_NONE 无效 */
        wire_t          frame;         /* 参照系接线；FRAME_WORLD 表示世界系 */
        uint64_t        issued_at_ns;  /* 事件发出时刻（调用者时钟） */
        uint64_t        duration_ns;   /* 新鲜度窗口长度；0 的事件被拒绝 */
        uint8_t         dof;           /* 有效分量数，≤ MOTION_DOF_MAX */
        motion_fixed_t  motion[MOTION_DOF_MAX]; /* 相对 frame 的速度（决定 18） */
} motion_event_t;

/*
 * 「静止」不是一种指令，而是一个事件：
 *
 *     motion_event_t still = {
 *         .wire         = w,
 *         .frame        = FRAME_WORLD,
 *         .issued_at_ns = <发出时刻>,
 *         .duration_ns  = <新鲜度窗口>,
 *         .dof          = 0,
 *         .motion       = { 0 },
 *     };
 *
 * 即「相对参照系速度为零」。这就是「静止是一种相对的运动」。
 */

/* ------------------------------------------------------------------ */
/* 原语                                                                */
/* ------------------------------------------------------------------ */

typedef enum {
        MOTION_OK          =  0,
        MOTION_E_INVAL     = -1,  /* 参数非法（dof 越界、wire 无效…） */
        MOTION_E_NO_WIRE   = -2,  /* 目标接线不存在或已断开 */
        MOTION_E_NO_FRAME  = -3,  /* 参照系接线不存在或已断开 */
        MOTION_E_NO_OBJECT = -4,  /* 接线当前没有物件 */
        MOTION_E_DEADLINE  = -5,  /* 事件已过期：发出时刻 + 窗口早于提交时刻 */
        MOTION_E_LIMIT     = -6,  /* 命令幅值超出物件自报的最大速率（物件侧判定） */
} motion_status_t;

/*
 * 施加运动 —— 基座唯一的原语。
 *
 * now_ns 是事件到达本原语的提交时刻，由调用者提供。基座只把它作为
 * 本次调用的参数传给物件，不保存时间；因此新鲜度判断不会错误复用
 * 上一次 object_run 的旧节拍。过期事件以 MOTION_E_DEADLINE 拒绝；
 * 一旦接受，物件持续沿该事件运动。
 *
 * 基座自身只校验「事件形状」：dof 不越界、目标接线与参照接线当前有效。
 * 它不读 motion[]、不读能力申报、不知道 max_rate / 行程 / 姿态的存在，
 * 因此 MOTION_E_LIMIT 这类「物件按自身能力拒绝」的状态码由物件层产生，
 * 基座只是把它原样传回。这条分工由 make check-purity 静态断言。
 */
motion_status_t base_apply(u64 now_ns, const motion_event_t *ev);

/* ------------------------------------------------------------------ */
/* 接线                                                                */
/*                                                                    */
/* 接线是「谁挂在哪个口」。它不是世界信息，是执行的必要条件。          */
/*                                                                    */
/* 基座对一条接线只知道一件事：它此刻是否活着。单位、控制周期等自述    */
/* 属性由物件自己保存、供大脑直读（设计决定 17），不交给基座。         */
/* ------------------------------------------------------------------ */

/*
 * 物件到达 —— 一条接线由此产生。
 *
 * 这是接线**唯一**的来源。总线驱动（如 PCI 枚举）发现一个物件后调用它；
 * 没有别的路径可以凭空造出一条接线。这样「插上就被识别」才成立：
 * 识别的结果就是这里返回的句柄。
 *
 * 不带任何参数：到达本身就是全部内容。
 * 成功返回分配给该物件的接线句柄，失败（表满）返回 WIRE_NONE。
 */
wire_t base_arrive(void);

/*
 * 基座初始化：清空接线表。
 *
 * 裸机引导器不一定会把 .bss 清零，而接线表的状态直接决定
 * 一个口上有没有物件。启动时显式调用一次。
 */
void base_init(void);

/* 物件离开。此后该接线上的任何运动事件都会以 E_NO_WIRE 拒绝。 */
void base_depart(wire_t w);

/* 接线当前是否有效（仅查询接线本身，不涉及世界状态）。 */
bool base_wire_valid(wire_t w);

#endif /* LITEOS_BASE_H */