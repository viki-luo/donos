/*
 * mo_standard.h — DONOS-MO-1：运动物件接口标准
 *
 * 标准的目的是让系统**不问「你是什么」**：
 *   不管是轮子、关节、推进器、舵机，还是别的东西，只要符合本标准的
 *   数值约定与行为条款，就能被识别、被命令、被观察；
 *   系统不需要知道它的类型、用途、机械结构或控制算法。
 *
 * 因此本标准里**没有设备类型字段**。一旦有「type = wheel / joint」，
 * 基座就要开始理解这些名字的含义，那就已经违反了运动控制的单一职责，
 * 也把「新设备必须改内核」写进了架构。
 *
 * --------------------------------------------------------------------
 * 第一部分：数值约定（Numeric contract）
 * --------------------------------------------------------------------
 *
 *  Q-1  所有运动量都是 Q32.32 定点数，禁止浮点参与命令与状态。
 *  Q-2  单位固定为 SI：线速度 m/s、角速度 rad/s、位置 m、姿态单位四元数。
 *  Q-3  time 一律是纳秒、单调不减；不允许把负数或未来的时刻当作「现在」。
 *  Q-4  方向由符号表达：倒车是负的线速度，反转是负的角速度；
 *       标准里**没有**「倒车指令」这种独立操作。
 *
 * --------------------------------------------------------------------
 * 第二部分：设备必须提供的接口（Required interface）
 * --------------------------------------------------------------------
 *
 *  D-1  set_velocity(linear[3], angular[3]) → bool
 *       接收本物件**相对其 frame** 的速度。返回 false 表示拒绝或离线，
 *       但不得因此伪造一份实测。
 *  D-2  sample(object_state_t *out) → bool
 *       读回实测位姿与速度，并且**覆盖 out 的全部字段**。
 *       返回 false 表示读不到；调用者保持上一次的实测值。
 *  D-3  两个回调都不得阻塞超过本物件申报的 period_ns。
 *  D-4  实现不得要求基座或上层大脑知道设备类型。
 *
 * --------------------------------------------------------------------
 * 第三部分：行为条款（Behavioural clauses，逐条可机检）
 * --------------------------------------------------------------------
 *
 *  S-1  自描述：物件必须先申报能力（dof、period_ns），才可能被推进。
 *  S-2  拒绝而非钳制：越界命令整条拒绝，绝不悄悄钳到一个「差不多」的值。
 *  S-3  实测独立：sample 必须反映传感器真值，不能回显上一条命令。
 *       —— 这条是偏差检测能否成立的根本前提。
 *  S-4  失效诚实：读失败返回 false，保持上次实测；绝不把「没有数据」
 *       报成零速度（那会让监视器以为物件已经停住）。
 *  S-5  单位不泄漏：轮径、减速比、编码器线数、关节零位只存在于设备实现，
 *       不得出现在事件里，也不得要求大脑换算。
 *  S-6  无类型：系统在任何一条路径上都不需要知道设备是什么。
 *  S-7  首次不积分：第一次被看见只排期，不把从未经过的时间算进位置。
 *  S-8  热拔插：离开的接线永不复活；复用槽位不继承上一任设备。
 *
 * --------------------------------------------------------------------
 * 第四部分：一致性（Conformance）
 * --------------------------------------------------------------------
 *
 *  一个实现只有通过了 `tests/host/conformance_mo.c` 的全部条款，才可
 *  声明自己符合 DONOS-MO-1。测试套件是设备无关的：它接收一个设备描述，
 *  用同一组条款跑任何一个实现 —— 车轮与关节跑的是同一份套件，
 *  这正是「系统不问是什么」的证据。
 */
#ifndef DONOS_MO_STANDARD_H
#define DONOS_MO_STANDARD_H

#include "motion_device.h"

/* 标准版本：不兼容变更时递增主号。 */
#define DONOS_MO1_VERSION_MAJOR 1
#define DONOS_MO1_VERSION_MINOR 0

/* 数值约定的编号。用于测试输出与文档互相引用，避免「说过但没测」。 */
typedef enum {
        MO_Q1_FIXED_ONLY = 1,
        MO_Q2_SI_UNITS,
        MO_Q3_MONOTONIC_TIME,
        MO_Q4_SIGN_IS_DIRECTION,

        MO_D1_SET_VELOCITY = 16,
        MO_D2_SAMPLE_OVERWRITES,
        MO_D3_NO_BLOCKING,
        MO_D4_NO_TYPE_KNOWLEDGE,

        MO_S1_DECLARE_FIRST = 32,
        MO_S2_REFUSE_NOT_CLAMP,
        MO_S3_MEASURED_IS_INDEPENDENT,
        MO_S4_FAILURE_IS_HONEST,
        MO_S5_NO_UNIT_LEAK,
        MO_S6_NO_TYPE,
        MO_S7_FIRST_SIGHTING_SCHEDULES,
        MO_S8_HOT_PLUG_SAFE,
} mo_clause_t;

/* 条款的机器可读名称，测试失败时打印，避免只报编号。 */
const char *mo_clause_name(mo_clause_t clause);

#endif /* DONOS_MO_STANDARD_H */
